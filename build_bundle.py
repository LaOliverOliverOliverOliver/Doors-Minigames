# Creates bundle.js: a snapshot of every .json in properties/entities and properties/items.
# The game only uses it when it can't read the folders live (opening index.html by double-click, or GitHub rate limits).
# serve.py runs this automatically every time it starts. You can also run:  python build_bundle.py
import json, os
ROOT = os.path.dirname(os.path.abspath(__file__))

def main():
    out = {}
    for sec in ("entities", "items"):
        folder = os.path.join(ROOT, "properties", sec)
        rows = []
        for f in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            p = os.path.join(folder, f)
            if not f.lower().endswith(".json"):
                if os.path.isfile(p) and not f.lower().startswith("readme"):
                    print(f"  warning: properties/{sec}/{f} is not a .json file, so the game ignores it")
                continue
            try:
                with open(p, encoding="utf-8") as fh:
                    rows.append(json.load(fh))
            except Exception as e:
                print(f"  warning: properties/{sec}/{f} is not valid JSON ({e})")
        out[sec] = rows
    with open(os.path.join(ROOT, "bundle.js"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_bundle.py - do not edit by hand.\nconst BUNDLE = " + json.dumps(out, ensure_ascii=False) + ";\n")
    return {k: len(v) for k, v in out.items()}

if __name__ == "__main__":
    print("bundle.js updated:", main())
